// The people who make the games.
//
// An easter egg, and the one list in the app that is neither transcribed from
// the rulebook nor lifted off a wiki: ten indie wargame designers, checked
// against their publishers rather than remembered. It is used in two places -
// as capital-ship names in the UNSC fleet, where naming a hull after a person
// is already the tradition (the Halopedia pool carries Carl Sagan, Meriwether
// Lewis and Phyllis Wheatley), and as a rare culture in the HVP name roller,
// where any human faction can turn one up as a person.
//
// Who they are, so nobody has to guess later:
//
//   Mike Hutchinson    A Billion Suns and Gaslands, Planet Smasher Games. This
//                      app is a builder for his game; he goes first.
//   Jet Wong           WarLore. Built this.
//   Sean Sutter        Relicblade and SLUDGE, Metal King Studio - a one-person
//                      operation, rules and sculpts and illustration alike.
//   Gavin Moorcroft    Relics, Tor Gaming.
//   Gregory Horton     Electi Studio, and Blaster, which publishes a new indie
//                      game every volume.
//   David Lewis        Dropzone Commander and Dropfleet Commander, Hawk
//                      Wargames. Three years on the first game, doing the
//                      rules, sculpts, painting and photography himself.
//   Andy Chambers      Dropfleet Commander with Lewis, and Battlefleet Gothic
//                      before it - the other great fleet game in this shape.
//   Ash Barker         Steel Rift's original groundwork, and Guerrilla
//                      Miniature Games.
//   Daniel Mersey      Lion Rampant, Dragon Rampant, Xenos Rampant. Osprey,
//                      same shelf as A Billion Suns.
//   Joseph McCullough  Frostgrave, Stargrave, Rangers of Shadow Deep.
//
// Add to it freely; it is meant to grow.

